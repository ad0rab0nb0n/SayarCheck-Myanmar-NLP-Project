import json
import re
from symspellpy import SymSpell


# ============================================================
# CONFIGURATION
# ============================================================

DICTIONARY_PATH = "preprocessing/spelling_dictionary.json"


# ============================================================
# LOAD WORD FREQUENCIES
# ============================================================

with open(
    DICTIONARY_PATH,
    "r",
    encoding="utf-8"
) as f:

    word_frequencies = json.load(f)


# ============================================================
# CREATE SYMSPELL
# ============================================================

sym_spell = SymSpell(
    max_dictionary_edit_distance=2,
    prefix_length=7
)


for word, frequency in word_frequencies.items():

    # Skip very short entries
    if len(word) < 2:
        continue

    # Myanmar words only
    if not re.search(
        r"[\u1000-\u109F]",
        word
    ):
        continue

    # Skip words containing Latin characters
    if re.search(
        r"[A-Za-z]",
        word
    ):
        continue

    sym_spell.create_dictionary_entry(
        word,
        frequency
    )


print("Spelling dictionary loaded.")
print(
    "Unique words:",
    len(word_frequencies)
)


# ============================================================
# SYMSPELL CANDIDATES
# ============================================================

def check_spelling(
    word,
    max_suggestions=5
):

    suggestions = sym_spell.lookup(
        word,
        verbosity=2,
        max_edit_distance=2
    )

    results = []

    for suggestion in suggestions[:max_suggestions]:

        results.append({

            "word":
                suggestion.term,

            "distance":
                suggestion.distance,

            "frequency":
                suggestion.count

        })

    return results


# ============================================================
# CORRECT ONE WORD
# ============================================================

def correct_word(word):

    suggestions = check_spelling(
        word,
        max_suggestions=5
    )

    # No candidates
    if not suggestions:
        return word

    best = suggestions[0]

    # Distance 0 = already a dictionary word
    if best["distance"] == 0:
        return word

    # Automatically correct only
    # very close candidates
    if best["distance"] == 1:
        return best["word"]

    # Do not make uncertain corrections
    return word


