# ============================================================
# APPLY CONTEXT RULES
# ============================================================

def apply_context_rules(text):

    corrected_text = text

    for wrong_phrase, correct_phrase in CONTEXT_RULES.items():

        corrected_text = corrected_text.replace(
            wrong_phrase,
            correct_phrase
        )

    return corrected_text


# ============================================================
# AUTOMATIC SPELLING CORRECTION
# ============================================================

def correct_text(text):

    # --------------------------------------------------------
    # Step 1:
    # Apply context-aware phrase corrections
    # --------------------------------------------------------

    text = apply_context_rules(text)


    # --------------------------------------------------------
    # Step 2:
    # Correct whitespace-separated words with SymSpell
    # --------------------------------------------------------

    words = text.split()

    corrected_words = []

    for word in words:

        # Separate punctuation at the end temporarily
        punctuation = ""

        match = re.match(
            r"^(.*?)([၊။,!?\.\:;]+)$",
            word
        )

        if match:

            word_without_punctuation = match.group(1)

            punctuation = match.group(2)

        else:

            word_without_punctuation = word


        # Empty word
        if not word_without_punctuation:

            corrected_words.append(word)

            continue


        # SymSpell correction
        corrected_word = correct_word(
            word_without_punctuation
        )


        corrected_words.append(
            corrected_word + punctuation
        )


    # --------------------------------------------------------
    # Step 3:
    # Reconstruct sentence
    # --------------------------------------------------------

    return " ".join(
        corrected_words
    )


# ============================================================
# SPELLING CHECK
# ============================================================

def spelling_check_word(word):

    suggestions = check_spelling(
        word,
        max_suggestions=5
    )

    if not suggestions:

        return {

            "word":
                word,

            "correct":
                True,

            "suggestions":
                []

        }


    best = suggestions[0]


    # Dictionary word
    if (
        best["word"] == word
        and best["distance"] == 0
    ):

        return {

            "word":
                word,

            "correct":
                True,

            "suggestions":
                []

        }


    return {

        "word":
            word,

        "correct":
            False,

        "suggestions":
            suggestions

    }


